let currentLang = localStorage.getItem('tm_lang') || 'en';

window.setLanguage = function(lang) {
  if (!translations[lang]) lang = 'en';
  currentLang = lang;
  localStorage.setItem('tm_lang', lang);
  updatePageTranslations();
  
  // Custom event to trigger re-renders if necessary
  window.dispatchEvent(new Event('languageChanged'));
};

window.t = function(key) {
  const dict = translations[currentLang] || translations['en'];
  return dict[key] || translations['en'][key] || key;
};

function updatePageTranslations() {
  const dict = translations[currentLang] || translations['en'];
  
  // 1. Explicit data-i18n attributes
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.getAttribute('data-i18n');
    if (el.tagName === 'INPUT' && el.type === 'button') {
      el.value = t(key);
    } else if (el.tagName === 'INPUT' || el.tagName === 'TEXTAREA') {
      el.placeholder = t(key);
    } else {
      if (el.hasAttribute('data-i18n-html')) {
        el.innerHTML = t(key);
      } else {
        el.textContent = t(key);
      }
    }
  });

  // 2. Auto-translate exact text matches (very useful for static HTML)
  // Build a reverse lookup from English string to key
  const reverseEn = {};
  for (const k in translations.en) {
    reverseEn[translations.en[k]] = k;
  }

  function walkAndTranslate(node) {
    if (node.nodeType === Node.TEXT_NODE) {
      const originalText = node.nodeValue.trim();
      if (originalText && reverseEn[originalText]) {
        // We found an exact match to an English string!
        // Save the key on the parent element so we can re-translate it later if language changes
        if (node.parentElement && !node.parentElement.hasAttribute('data-i18n')) {
            node.parentElement.setAttribute('data-i18n', reverseEn[originalText]);
            node.nodeValue = t(reverseEn[originalText]);
        }
      }
    } else if (node.nodeType === Node.ELEMENT_NODE) {
      // Also auto-translate placeholders
      if ((node.tagName === 'INPUT' || node.tagName === 'TEXTAREA') && node.placeholder) {
        if (reverseEn[node.placeholder]) {
           node.setAttribute('data-i18n', reverseEn[node.placeholder]);
           node.placeholder = t(reverseEn[node.placeholder]);
        }
      }
      // Skip script, style, and already translated elements
      if (node.tagName !== 'SCRIPT' && node.tagName !== 'STYLE' && !node.hasAttribute('data-i18n')) {
        for (let i = 0; i < node.childNodes.length; i++) {
          walkAndTranslate(node.childNodes[i]);
        }
      }
    }
  }
  
  walkAndTranslate(document.body);
}

// Add UI Switcher automatically
document.addEventListener('DOMContentLoaded', () => {
  if (window.location.pathname.includes('/judge.html') || window.location.pathname.endsWith('/judge') || document.getElementById('judge-tablet-layout')) {
    updatePageTranslations();
    return;
  }
  const switcher = document.createElement('div');
  switcher.id = 'language-switcher-widget';
  switcher.style.cssText = 'position:fixed; bottom:20px; right:20px; z-index:999999; display:flex; flex-direction:column-reverse; gap:8px; background:rgba(0,0,0,0.7); padding:8px; border-radius:30px; backdrop-filter:blur(10px); border:1px solid rgba(255,255,255,0.15); transition:all 0.3s ease; align-items:center; height: 36px; overflow:hidden; box-shadow: 0 10px 25px rgba(0,0,0,0.5);';
  
  const langs = [
    { code: 'en', flag: '🇬🇧', title: 'English' },
    { code: 'ka', flag: '🇬🇪', title: 'ქართული' },
    { code: 'ru', flag: '🇷🇺', title: 'Русский' }
  ];
  
  switcher.onmouseenter = () => { switcher.style.height = (16 + langs.length * 36) + 'px'; };
  switcher.onmouseleave = () => { switcher.style.height = '36px'; };

  function renderButtons() {
    switcher.innerHTML = '';
    
    // Sort so current language is at the bottom (first in column-reverse)
    const sorted = [...langs].sort((a, b) => {
      if (a.code === currentLang) return -1;
      if (b.code === currentLang) return 1;
      return 0;
    });

    sorted.forEach(l => {
      const btn = document.createElement('button');
      btn.textContent = l.flag;
      btn.title = l.title;
      const isCurrent = currentLang === l.code;
      btn.style.cssText = `background:none; border:none; cursor:pointer; font-size:20px; width:36px; height:36px; display:flex; align-items:center; justify-content:center; padding:0; filter: ${isCurrent ? 'grayscale(0)' : 'grayscale(0.8) opacity(0.7)'}; transition:all 0.2s; border-radius:50%;`;
      
      btn.onmouseenter = () => { if (!isCurrent) btn.style.filter = 'grayscale(0) opacity(1)'; };
      btn.onmouseleave = () => { if (!isCurrent) btn.style.filter = 'grayscale(0.8) opacity(0.7)'; };
      
      btn.onclick = () => {
        setLanguage(l.code);
        renderButtons(); // Re-render to put new current lang at bottom
        switcher.style.height = '36px'; // Collapse on click
      };
      switcher.appendChild(btn);
    });
  }
  
  renderButtons();
  document.body.appendChild(switcher);
  updatePageTranslations();
});
